const TS: Record<Abi, string> = { f64: 'number', u32: 'number', i32: 'number', bool: 'boolean', string: 'string', bytes: 'Uint8Array', void: 'void' };

const manifest: unknown[] = [];
let ts = `/* Generated by src/scriptc/gen-ffi.ts from its table. Do not edit. */\n`;
for (const [name, [params, returns]] of Object.entries(FUNCTIONS)) {
	const m_params: unknown[] = [];
	const args: string[] = [];
	params.forEach((p, i) => {
		if (typeof p === 'string') {
			m_params.push(p);
			args.push(`a${i}: ${TS[p]}`);
			return;
		}
		m_params.push({
			callback: { id: p.cb, params: [...p.params, { context: p.cb }], returns: 'void', lifetime: p.retained ? 'retained' : 'call' }
		});
		m_params.push({ context: p.cb });
		args.push(`a${i}: (${p.params.map((t, k) => `p${k}: ${TS[t]}`).join(', ')}) => void`);
	});
	manifest.push({ name: `cuisvsc_${name}`, symbol: `cuisvsc_${name}`, params: m_params, returns });
	const names = params.map((_, i) => `a${i}`).join(', ');
	ts += `declare function cuisvsc_${name}(${args.join(', ')}): ${TS[returns]};\n`;
	ts += `export function ${name}(${args.join(', ')}): ${TS[returns]} {\n\t${returns === 'void' ? '' : 'return '}cuisvsc_${name}(${names});\n}\n`;
}

const dir = import.meta.dirname;
writeFileSync(join(dir, 'ffi.ts'), ts);
writeFileSync(join(dir, 'ffi.functions.json'), JSON.stringify(manifest, null, '\t') + '\n');
console.log(`${manifest.length} functions`);
